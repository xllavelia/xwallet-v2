// Подстраховка на случай, если сервер отдаёт ресурс под другим тикером:
// иконку берём по названию актива. Тикеры акций и монет надёжны, поэтому
// запасное сопоставление нужно только ресурсам (у них нет фирменного знака).
var RESOURCE_BY_WORD = [
  [["gold", "xau"], "GC=F"],
  [["silver", "xag"], "SI=F"],
  [["copper", "bronze"], "HG=F"],
  [["oil", "crude", "brent", "wti", "petroleum"], "CL=F"],
  [["gas", "lng"], "NG=F"],
  [["corn", "maize", "wheat", "grain", "oats"], "ZC=F"],
  [["platinum", "palladium"], "SI=F"]
];

function resourceByLabel(label) {
  var tokens = String(label || "").toLowerCase().split(/[^a-z0-9]+/);
  for (var i = 0; i < RESOURCE_BY_WORD.length; i++) {
    var words = RESOURCE_BY_WORD[i][0];
    for (var j = 0; j < words.length; j++) {
      if (tokens.indexOf(words[j]) !== -1) return RESOURCES[RESOURCE_BY_WORD[i][1]];
    }
  }
  return null;
}

function AssetLogo(props) {
  var code = String(props.code || "").toUpperCase();
  var crypto = CRYPTO[code];
  var stock = STOCKS[code];
  var resource = RESOURCES[code];
  if (!crypto && !stock && !resource) resource = resourceByLabel(props.label);
  var vb = "0 0 48 48";
  var body;

  if (crypto) {
    vb = crypto.vb;
    body = [
      <circle key="d" cx={crypto.cx} cy={crypto.cy} r={crypto.r} fill={crypto.disc} />,
      crypto.paths.map(function (p, i) { return <path key={i} d={p.d} fill={p.fill} fillOpacity={p.opacity} />; })
    ];
  } else if (stock) {
    var mark = stock.paths
      ? stock.paths.map(function (p, i) { return <path key={i} d={p.d} fill={p.fill} />; })
      : <path d={stock.d} fill={stock.fill} />;
    body = [
      <circle key="d" cx="24" cy="24" r="24" fill="#ffffff" />,
      <g key="m" transform="translate(8.6 8.6) scale(1.28)">{mark}</g>
    ];
  } else if (resource) {
    body = [
      <circle key="d" cx="24" cy="24" r="24" fill="#ffffff" />,
      resource.shapes.map(function (s, i) { return <path key={i} d={s.d} fill={s.fill} />; })
    ];
  } else {
    // Фолбэк для неизвестного тикера: не остаёмся совсем без иконки.
    body = [
      <circle key="d" cx="24" cy="24" r="24" fill="#2a2a2a" />,
      <text key="t" x="24" y="24" textAnchor="middle" dominantBaseline="central" fill="#f4f2ec" fontSize="15" fontFamily="'Unbounded', sans-serif">{(props.label || code || "?").slice(0, 2).toUpperCase()}</text>
    ];
  }

  return (
    <span className="asset-logo" style={{ display: "block", width: "100%", height: "100%", borderRadius: "50%", overflow: "hidden", lineHeight: 0 }}>
      <svg viewBox={vb} width="100%" height="100%" preserveAspectRatio="xMidYMid meet" style={{ display: "block" }}>{body}</svg>
    </span>
  );
}

